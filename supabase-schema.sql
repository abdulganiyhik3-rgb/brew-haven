create table if not exists public.products (
  id bigint generated by default as identity primary key,
  name text not null,
  description text not null default '',
  image_url text not null,
  price numeric(10, 2) not null check (price >= 0),
  is_available boolean not null default true,
  created_at timestamptz not null default now()
);

create table if not exists public.orders (
  id bigint generated by default as identity primary key,
  customer_name text not null,
  customer_email text not null default '',
  items jsonb not null,
  total numeric(10, 2) not null check (total >= 0),
  status text not null default 'new' check (status in ('new', 'preparing', 'ready', 'completed', 'cancelled')),
  payment_reference text unique,
  payment_status text not null default 'pending' check (payment_status in ('pending', 'paid', 'failed')),
  created_at timestamptz not null default now()
);

alter table public.orders add column if not exists customer_email text not null default '';
alter table public.orders add column if not exists payment_reference text unique;
alter table public.orders add column if not exists payment_status text not null default 'pending'
  check (payment_status in ('pending', 'paid', 'failed'));

create table if not exists public.posts (
  id bigint generated by default as identity primary key,
  title text not null,
  content text not null,
  author text not null default 'Brew Haven',
  created_at timestamptz not null default now()
);

alter table public.products enable row level security;
alter table public.orders enable row level security;
alter table public.posts enable row level security;

revoke all on public.products, public.orders, public.posts from anon, authenticated;

drop policy if exists "Public can read available products" on public.products;
create policy "Public can read available products"
  on public.products for select
  using (is_available = true);

drop policy if exists "Public can read posts" on public.posts;
create policy "Public can read posts"
  on public.posts for select
  using (true);

grant select on public.products, public.posts to anon, authenticated;

